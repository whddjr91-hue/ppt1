import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {parseMermaidStructure} from '../src/mermaid-structure.mjs';
import {createNativeDeck,validateProto} from '../src/native-pptx.mjs';
const base=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=path.resolve(base,'../../.local/advanced-tests/session3');await fs.mkdir(output,{recursive:true});
const source='flowchart LR\n A["원고"] --> B["장면"]\n B --> C["화면"]';
const graph=await parseMermaidStructure(source);
assert.equal(graph.nodes.length,3);assert.equal(graph.edges.length,2);assert.equal(graph.nodes[0].label,'원고');assert.equal(graph.edges[1].to,'C');
const rejectionCases=['flowchart XX\n A -->','sequenceDiagram\n A->>B: check','flowchart LR\n click A callback','flowchart LR\n subgraph S\n A-->B\n end'];
for(const invalid of rejectionCases)await assert.rejects(()=>parseMermaidStructure(invalid));
await fs.writeFile(path.join(output,'structure.mmd'),source+'\n');await fs.writeFile(path.join(output,'structure.json'),JSON.stringify(graph,null,2)+'\n');
const summaries=[];
for(const family of ['KIRD','KEDI']){
 const proto=JSON.parse(await fs.readFile(path.join(base,'fixtures',family.toLowerCase()+'-virtual-proto.json'),'utf8'));const k=proto.width/10;
 assert.throws(()=>validateProto({...proto,diagnosticOnly:false}));
 assert.throws(()=>validateProto({...proto,width:1}));
 const deck=createNativeDeck(proto);const box=(x,y,w,h)=>({x:x*k,y:y*k,w:w*k,h:h*k});
 assert.throws(()=>deck.addScene({title:'guard',narration:'test',sceneId:'guard',speaker:'test',cues:[{id:2}]}));
 assert.throws(()=>deck.addScene({title:'guard',narration:'#1 test',sceneId:'guard',speaker:'test'}));
 assert.throws(()=>deck.shape({},'rect',box(9,1,2,1)));
 let slide=deck.addScene({title:`가상 ${family} 진단 / 비납품 / 객체 시험`,narration:'#1 도형·표·차트·SVG의 기본 출력을 확인합니다.',sceneId:'DIAGNOSTIC-OBJECTS',speaker:'시험용',cues:[{id:1,trigger:'도형'}]});
 deck.text(slide,'편집 가능한 텍스트와 도형',box(.5,1.12,6.9,.45),{fontSize:20*k});
 deck.shape(slide,deck.pptx.ShapeType.ellipse,box(.6,1.85,.6,.6),{fill:{color:proto.colors.accent},line:{color:proto.colors.accent}});
 deck.text(slide,'진단 도형',box(1.4,1.95,3.0,.4));
 deck.addTable(slide,[['항목','진단값'],['텍스트','수정 가능'],['표','네이티브']],box(.6,2.75,3.8,1.0),{colW:[1.5*k,2.3*k],rowH:.35*k});
 deck.addChart(slide,[{name:'진단값',labels:['가','나','다'],values:[2,4,3]}],box(4.8,1.95,4.35,2.25));
 const svg='<svg xmlns="http://www.w3.org/2000/svg" width="120" height="60" viewBox="0 0 120 60"><rect x="2" y="2" width="116" height="56" fill="#FFFFFF" stroke="#2878A5" stroke-width="3"/><path d="M20 30 L45 45 L95 15" fill="none" stroke="#2878A5" stroke-width="6"/></svg>';
 deck.addSvg(slide,svg,box(8.1,1.1,1.1,.55));
 slide=deck.addScene({title:`가상 ${family} 진단 / 비납품 / Mermaid 구조`,narration:'#1 Mermaid로 관계를 확인하고 PPT 도형과 텍스트로 작성합니다.',sceneId:'DIAGNOSTIC-MERMAID',speaker:'시험용',cues:[{id:1,trigger:'Mermaid'}]});
 deck.text(slide,'원고와 장면의 관계',box(.6,1.15,8.7,.5),{fontSize:22*k});
 const placements={A:box(.8,2.2,2.2,.8),B:box(3.9,2.2,2.2,.8),C:box(7.0,2.2,2.2,.8)};
 await deck.addMermaidNative(slide,source,placements,{text:{fontSize:20*k}});
 await assert.rejects(()=>deck.addMermaidNative(slide,source,{}));
 deck.text(slide,'진단용 수치·문구이며 기존 원고와 무관합니다.',box(.7,3.7,8.6,.4));
 const file=path.join(output,family.toLowerCase()+'-virtual-diagnostic.pptx');
 const receipt=await deck.save(file);await fs.writeFile(file+'.receipt.json',JSON.stringify(receipt,null,2)+'\n');
 summaries.push({family,file,width:proto.width,height:proto.height,slides:2,svgFallbacks:receipt.svgFallbacks.length});
}
await fs.writeFile(path.join(output,'execution.json'),JSON.stringify({diagnosticOnly:true,mermaid:{nodes:3,edges:2,koreanLabels:true,invalidOrUnsupportedRejected:rejectionCases.length},summaries},null,2)+'\n');
console.log(JSON.stringify({passed:true,summaries}));
